import { INTERNAL_WEIGHT_PRECISION } from '@/constants/precision'
import { getMaterialCategoryOptions } from '@/module-system/core/module-option-resolvers'
import type { MasterFormFieldSpec, MasterOption } from './master-data-types'

/** 物理属性字段是否可见：附加费用类只需要名称/单位/单价。 */
const physicalVisibleWhen = (values: Record<string, unknown>) =>
  values.materialType !== '附加费用'

/**
 * 商品表单字段定义。附加费用类仍需填写“名称”、单位与单价，
 * 物理属性字段（品牌/规格/长度/数量单位/件重/支数）与类别均隐藏，
 * 类别由后端固定写入“附加费用”。
 *
 * <p>放在非组件模块：这是纯字段声明，组件与它的测试都直接引用同一份定义。</p>
 */
export function buildMaterialFormFields(
  t: (key: string) => string,
  materialTypeOptions: MasterOption[],
): MasterFormFieldSpec[] {
  return [
    {
      section: t('modules.formSections.basic'),
      key: 'materialType',
      label: t('modules.pages.material.materialType'),
      type: 'select',
      required: true,
      defaultValue: '实体商品',
      options: materialTypeOptions,
    },
    {
      section: t('modules.formSections.basic'),
      key: 'materialCode',
      label: t('modules.pages.material.materialCode'),
      type: 'input',
      disabled: true,
      placeholder: t('modules.editorWorkspace.autoGeneratedPlaceholder'),
    },
    {
      section: t('modules.formSections.basic'),
      key: 'brand',
      label: t('modules.pages.material.brand'),
      type: 'input',
      required: true,
      maxLength: 64,
      visibleWhen: physicalVisibleWhen,
    },
    {
      section: t('modules.formSections.basic'),
      key: 'material',
      label: t('modules.pages.material.material'),
      type: 'input',
      required: true,
      maxLength: 16,
    },
    {
      section: t('modules.formSections.basic'),
      key: 'category',
      label: t('modules.pages.material.category'),
      type: 'select',
      required: true,
      options: getMaterialCategoryOptions(),
      visibleWhen: physicalVisibleWhen,
    },
    {
      section: t('modules.formSections.basic'),
      key: 'spec',
      label: t('modules.pages.material.spec'),
      type: 'input',
      required: true,
      maxLength: 64,
      visibleWhen: physicalVisibleWhen,
    },
    {
      section: t('modules.formSections.basic'),
      key: 'length',
      label: t('modules.pages.material.length'),
      type: 'input',
      required: true,
      maxLength: 32,
      visibleWhen: physicalVisibleWhen,
    },
    {
      section: t('modules.formSections.basic'),
      key: 'unit',
      label: t('modules.pages.material.unit'),
      type: 'input',
      required: true,
      maxLength: 8,
    },
    {
      section: t('modules.formSections.weightPrice'),
      key: 'quantityUnit',
      label: t('modules.pages.material.qtyUnit'),
      type: 'input',
      required: true,
      maxLength: 8,
      visibleWhen: physicalVisibleWhen,
    },
    {
      section: t('modules.formSections.weightPrice'),
      key: 'pieceWeightTon',
      label: t('modules.pages.material.pieceWeightTon'),
      type: 'number',
      required: true,
      min: 0,
      precision: INTERNAL_WEIGHT_PRECISION,
      defaultValue: 0,
      visibleWhen: physicalVisibleWhen,
    },
    {
      section: t('modules.formSections.weightPrice'),
      key: 'piecesPerBundle',
      label: t('modules.pages.material.pcsPerBundle'),
      type: 'number',
      required: true,
      min: 0,
      precision: 0,
      defaultValue: 0,
      visibleWhen: physicalVisibleWhen,
    },
    {
      section: t('modules.formSections.weightPrice'),
      key: 'unitPrice',
      label: t('modules.pages.material.unitPrice'),
      type: 'number',
      required: true,
      min: 0,
      precision: 2,
      defaultValue: 0,
    },
    {
      section: t('modules.formSections.other'),
      key: 'remark',
      label: t('modules.pages.material.remark'),
      type: 'textarea',
      fullRow: true,
    },
  ]
}
