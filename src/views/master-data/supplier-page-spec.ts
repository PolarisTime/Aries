import type { TFunction } from 'i18next'
import type { ReactNode } from 'react'
import { enabledStatusOptions } from '@/constants/module-options'
import { STATUS } from '@/constants/status-constants'
import { asString } from '@/utils/type-narrowing'
import type { MasterDataPageSpec, MasterOption } from './master-data-types'

const asBrandList = (value: unknown): string[] =>
  Array.isArray(value)
    ? value.flatMap((item) => {
        const brand = asString(item).trim()
        return brand ? [brand] : []
      })
    : []

function formatBrands(value: unknown): ReactNode {
  const brands = asBrandList(value)
  return brands.length ? brands.join('、') : '-'
}

/**
 * 供方资料列表页配置（列定义、筛选、表单字段与记录映射）。
 *
 * <p>放在非组件模块：这是纯声明与纯映射，页面组件只负责取品牌选项后交给它。</p>
 */
export function buildSupplierSpec(
  t: TFunction,
  brandOptions: MasterOption[],
): MasterDataPageSpec {
  return {
    moduleKey: 'supplier',
    primaryNoKey: 'supplierCode',
    title: t('modules.pages.supplier.title'),
    description: t('modules.pages.supplier.description'),
    keywordPlaceholder: t('modules.pages.supplier.placeholderKeyword'),
    filters: [
      {
        key: 'status',
        type: 'select',
        placeholder: t('modules.filter.status'),
        options: enabledStatusOptions,
      },
    ],
    columns: [
      {
        key: 'supplierCode',
        title: t('modules.pages.supplier.colSupplierCode'),
        width: 140,
      },
      {
        key: 'supplierName',
        title: t('modules.pages.supplier.colSupplierName'),
        width: 180,
      },
      {
        key: 'shortName',
        title: t('modules.pages.supplier.colShortName'),
        width: 120,
      },
      {
        key: 'brands',
        title: t('modules.pages.supplier.colBrands'),
        width: 200,
        render: (row) => formatBrands(row.brands),
      },
      {
        key: 'contactName',
        title: t('modules.pages.supplier.colContactName'),
        width: 110,
      },
      {
        key: 'contactPhone',
        title: t('modules.pages.supplier.colContactPhone'),
        width: 140,
      },
      {
        key: 'city',
        title: t('modules.pages.supplier.colCity'),
        width: 120,
      },
      {
        key: 'status',
        title: t('modules.columns.status'),
        width: 100,
        align: 'center',
        status: true,
      },
      {
        key: 'remark',
        title: t('modules.columns.remark'),
        width: 180,
      },
    ],
    defaultHiddenColumnKeys: ['brands', 'contactPhone', 'city', 'remark'],
    detailFields: [
      {
        key: 'supplierCode',
        label: t('modules.pages.supplier.colSupplierCode'),
      },
      {
        key: 'supplierName',
        label: t('modules.pages.supplier.colSupplierName'),
      },
      {
        key: 'shortName',
        label: t('modules.pages.supplier.colShortName'),
      },
      {
        key: 'brands',
        label: t('modules.pages.supplier.colBrands'),
        render: (row) => formatBrands(row.brands),
      },
      {
        key: 'contactName',
        label: t('modules.pages.supplier.colContactName'),
      },
      {
        key: 'contactPhone',
        label: t('modules.pages.supplier.colContactPhone'),
      },
      { key: 'city', label: t('modules.pages.supplier.colCity') },
      {
        key: 'status',
        label: t('modules.columns.status'),
        status: true,
      },
      { key: 'remark', label: t('modules.columns.remark') },
    ],
    formFields: [
      {
        section: t('modules.formSections.basic'),
        key: 'supplierCode',
        label: t('modules.pages.supplier.colSupplierCode'),
        type: 'input',
        disabled: true,
        placeholder: t('modules.editorWorkspace.autoGeneratedPlaceholder'),
      },
      {
        section: t('modules.formSections.basic'),
        key: 'supplierName',
        label: t('modules.pages.supplier.colSupplierName'),
        type: 'input',
        required: true,
      },
      {
        section: t('modules.formSections.basic'),
        key: 'shortName',
        label: t('modules.pages.supplier.colShortName'),
        type: 'input',
      },
      {
        // 基本信息按四列栅格排：编码/名称/简称/城市 一行四个，
        // 状态 + 经营品牌（三列宽，多选标签需要位置）占第二行，右侧不留空列。
        section: t('modules.formSections.basic'),
        key: 'city',
        label: t('modules.pages.supplier.colCity'),
        type: 'input',
      },
      {
        section: t('modules.formSections.basic'),
        key: 'status',
        label: t('modules.columns.status'),
        type: 'select',
        defaultValue: STATUS.NORMAL,
        options: enabledStatusOptions,
      },
      {
        section: t('modules.formSections.basic'),
        key: 'brands',
        label: t('modules.pages.supplier.colBrands'),
        type: 'select',
        multiple: true,
        span: 18,
        placeholder: t('modules.pages.supplier.brandsPlaceholder'),
        options: brandOptions,
      },
      {
        section: t('modules.formSections.contact'),
        key: 'contactName',
        label: t('modules.pages.supplier.colContactName'),
        type: 'input',
      },
      {
        section: t('modules.formSections.contact'),
        key: 'contactPhone',
        label: t('modules.pages.supplier.colContactPhone'),
        type: 'input',
      },
      {
        section: t('modules.formSections.other'),
        key: 'remark',
        label: t('modules.columns.remark'),
        type: 'textarea',
        fullRow: true,
      },
    ],
    rowHighlightStatuses: [STATUS.DISABLED],
    buildValues: (record) => ({
      supplierCode: asString(record?.supplierCode),
      supplierName: asString(record?.supplierName),
      shortName: asString(record?.shortName),
      brands: asBrandList(record?.brands),
      contactName: asString(record?.contactName),
      contactPhone: asString(record?.contactPhone),
      city: asString(record?.city),
      status: asString(record?.status) || STATUS.NORMAL,
      remark: asString(record?.remark),
    }),
    buildRecord: (values, base) => ({
      ...(base ?? {}),
      supplierCode: asString(values.supplierCode),
      supplierName: values.supplierName,
      shortName: values.shortName ?? '',
      brands: asBrandList(values.brands),
      contactName: values.contactName ?? '',
      contactPhone: values.contactPhone ?? '',
      city: values.city ?? '',
      status: values.status,
      remark: values.remark ?? '',
    }),
  }
}
